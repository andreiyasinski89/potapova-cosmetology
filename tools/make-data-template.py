def style_cell(c, kind=None, bold=False, color='000000', italic=False, size=10):
    c.font = Font(name=F, size=size, bold=bold, italic=italic, color=color)
    c.alignment = WRAP
    c.border = BORDER
    if kind == 'ans': c.fill = ANS
    elif kind == 'ex': c.fill = EXA
    elif kind == 'known': c.fill = KNOWN
    elif kind == 'sect': c.fill = SECT

def title(ws, text, sub, ncols):
    ws['A1'] = text
    ws['A1'].font = Font(name=F, size=14, bold=True, color='0B2224')
    ws['A2'] = sub
    ws['A2'].font = Font(name=F, size=10, italic=True, color='595959')
