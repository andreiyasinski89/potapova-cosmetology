def qa_sheet(name, ttl, sub, rows, dv_lists=None):
    """rows: ('S', 'Раздел') или (что, зачем, пример, сейчас, [список для выбора])"""
    ws = wb.create_sheet(name)
    title(ws, ttl, sub, len(COLS))
    header(ws, 4, COLS, WID)
    r, n = 5, 0
    first, last = 5, 5
    for row in rows:
        if row[0] == 'S':
            ws.cell(row=r, column=1, value=None)
            c = ws.cell(row=r, column=2, value=row[1])
            for col in range(1, len(COLS) + 1):
                style_cell(ws.cell(row=r, column=col), 'sect', bold=(col == 2))
            r += 1
            continue
        what, why, ex, now = row[0], row[1], row[2], row[3]
        opts = row[4] if len(row) > 4 else None
        n += 1
        vals = [n, what, why, ex, now, None, None]
        for col, v in enumerate(vals, 1):
            c = ws.cell(row=r, column=col, value=v)
            kind = 'ans' if col == 6 else ('known' if col == 5 and v else ('ex' if col == 4 else None))
            style_cell(c, kind, italic=(col == 4))
        if opts:
            dv = DataValidation(type='list', formula1='"' + ','.join(opts) + '"', allow_blank=True)
            ws.add_data_validation(dv)
            dv.add(ws.cell(row=r, column=6))
        last = r
        r += 1
    return ws, first, last

